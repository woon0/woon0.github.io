import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
const browser=await puppeteer.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,pipe:true,args:['--no-sandbox','--disable-gpu']});
try {
 const page=await browser.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.setViewport({width:1440,height:1000});
 await page.goto('http://127.0.0.1:5174',{waitUntil:'networkidle0'});
 const path=()=>page.$eval('.surface-curve',e=>e.getAttribute('d'));
 const original=await path();
 const bounds=await page.$eval('.curiosity-form',e=>{const b=e.getBoundingClientRect();return{x:b.x,y:b.y,w:b.width,h:b.height};});
 await page.mouse.move(bounds.x+bounds.w*.8,bounds.y+bounds.h*.3);
 await page.waitForFunction(()=>document.querySelector('.curiosity-form').dataset.evolved==='true');
 assert.notEqual(await path(),original);
 await page.screenshot({path:'screenshot-curiosity-desktop.png'});
 await page.mouse.move(10,10);
 await page.waitForFunction(()=>document.querySelector('.curiosity-form').dataset.evolved==='false');
 const evolvedRest=await path(); assert.notEqual(evolvedRest,original);
 await page.focus('.curiosity-form'); await page.keyboard.press('ArrowRight');
 await page.waitForFunction(()=>document.querySelector('.curiosity-form').dataset.evolved==='true');
 await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
 const beforeReduced=await path(); await page.keyboard.press('ArrowLeft');
 await page.waitForFunction(previous=>document.querySelector('.surface-curve').getAttribute('d')!==previous,{},beforeReduced);
 await page.$eval('#work',el=>el.scrollIntoView({behavior:'instant'}));
 await page.screenshot({path:'screenshot-feathercut-project.png'});
 assert.equal(await page.$eval('.feather-window-name img',e=>e.complete&&e.naturalWidth>0),true);
 await page.click('.cover-feathercut');
 await page.waitForFunction(()=>{const img=document.querySelector('.product-screenshot img');return img?.complete&&img.naturalWidth>0;});
 await page.keyboard.press('Escape');
 await page.emulateMediaFeatures([{name:'prefers-color-scheme',value:'dark'}]);
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:'screenshot-curiosity-dark.png'});
 await page.setViewport({width:390,height:844,isMobile:true,hasTouch:true});
 await page.reload({waitUntil:'networkidle0'});
 await page.tap('.curiosity-form');
 await page.waitForFunction(()=>document.querySelector('.curiosity-form').dataset.evolved==='true');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'screenshot-curiosity-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: geometric deformation, evolved resting state, keyboard, reduced motion, touch, Feathercut assets and original screenshot, mobile bounds, no runtime errors.');
} finally {await browser.close();}
